#include "HumanA.hpp"
#include "HumanB.hpp"
#include "Weapon.hpp"

int main()
{
	/**
	 In which case is it appropriate to store the Weapon as a pointer ?
	 As a reference ? Why ? Is it the best choice in light of what’s asked ?
	 These are the questions you should ask yourself
	 before turning in this exercise.

	 ANSWER: In both cases, I store Weapon as a pointer,
	 because we can easily retrieve the original weapon object using
	 reference to reference (i.e get address of original object).

	 Of course, we could simply store &Weapon in Human A
	 to assign reference TO reference during construction, but this is messy
	 and gets harder to read for other engineers to understand.
	 */
	{
		Weapon	club = Weapon("crude spiked club");
		HumanA bob("Bob", club);
		bob.attack();
		club.setType("some other type of club");
		bob.attack();
	}
	{
		Weapon	club = Weapon("crude spiked club");
		HumanB jim("Jim");
		jim.setWeapon(club);
		jim.attack();
		club.setType("some other type of club");
		jim.attack();
	}
}